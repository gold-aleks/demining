def copy_photos():
    for id_, pairs in PHOTOS.items():
        for src_name, dest_name in pairs:
            src = os.path.join(EXTRACT, src_name)
            dest = os.path.join(PHOTO_DIR, dest_name)
            if not os.path.isfile(src):
                raise FileNotFoundError(src)
            shutil.copy2(src, dest)
            print("photo", dest_name)


def write_cards_and_index():
    os.makedirs(FUZE_DIR, exist_ok=True)
    idx = json.load(open(INDEX_PATH, encoding="utf-8"))
    existing_ids = {o["id"] for o in idx["objects"]}

    for card in CARDS:
        # clean empty weight
        if not card["technical"].get("weight"):
            card["technical"].pop("weight", None)
        path = os.path.join(FUZE_DIR, f"{card['id']}.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(card, f, ensure_ascii=False, indent=2)
            f.write("\n")
        thumb = card["media"]["photos"][0]["src"]
        entry = index_entry(card, thumb)
        if card["id"] in existing_ids:
            for i, o in enumerate(idx["objects"]):
                if o["id"] == card["id"]:
                    idx["objects"][i] = entry
                    break
        else:
            idx["objects"].append(entry)
            existing_ids.add(card["id"])
        print("card", card["id"], "->", path)

    with open(INDEX_PATH, "w", encoding="utf-8") as f:
        json.dump(idx, f, ensure_ascii=False, indent=2)
        f.write("\n")

    manifest = json.load(open(MANIFEST, encoding="utf-8"))
    for cat in manifest["categories"]:
        if cat["id"] == "fuzes":
            cat["count"] = len(idx["objects"])
    manifest["updated"] = UPDATED
    with open(MANIFEST, "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print("fuzes index count", len(idx["objects"]))
    print("added/updated", len(CARDS))


def main():
    assert len(CARDS) == 25, len(CARDS)
    copy_photos()
    write_cards_and_index()


if __name__ == "__main__":
    main()
