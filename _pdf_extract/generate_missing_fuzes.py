def media_photos(id_, captions):
    mapping = PHOTOS[id_]
    photos = []
    for i, (_src, dest) in enumerate(mapping):
        alt, cap = captions[i] if i < len(captions) else (dest, dest)
        photos.append(
            {
                "src": f"data/photos/{dest}",
                "alt": alt,
                "type": "photo",
                "caption": cap,
            }
        )
    return photos


